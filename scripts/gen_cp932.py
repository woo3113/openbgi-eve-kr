import io, os, sys
# Build a CP932 <-> Unicode table from Python's codec, emitted as a C header
# of sorted {sjis, unicode} pairs.  Used by the Android back end, which has
# no iconv CP932 support.
pairs = []
for hi in range(0x00, 0x100):
    for lo in range(0x00, 0x100):
        b = bytes([hi, lo])
        try:
            s = b.decode('cp932')
        except UnicodeDecodeError:
            continue
        if len(s) != 1:
            continue
        cp = ord(s)
        if cp == 0xFFFD:
            continue
        code = (hi << 8) | lo
        pairs.append((code, cp))
# one-byte ASCII/low range too (0x00..0xFF single bytes decode as latin1-ish in cp932)
for b in range(0x00, 0x100):
    try:
        s = bytes([b]).decode('cp932')
    except UnicodeDecodeError:
        continue
    if len(s) == 1 and ord(s) != 0xFFFD:
        pairs.append((b, ord(s)))
# dedupe by sjis code, keep first
seen = {}
for code, cp in pairs:
    if code not in seen:
        seen[code] = cp
items = sorted(seen.items())
out = io.StringIO()
out.write("/* Generated by scripts/gen_cp932.py from Python's cp932 codec - do not edit. */\n")
out.write("#ifndef BGI_ANDROID_CP932_TABLE_H_\n#define BGI_ANDROID_CP932_TABLE_H_\n")
out.write("#include <stdint.h>\n")
out.write("typedef struct { uint16_t sjis; uint16_t uni; } Cp932Pair_t;\n")
out.write("static const Cp932Pair_t kCp932Pairs[] = {\n")
for i, (code, cp) in enumerate(items):
    out.write("{0x%04x,0x%04x}," % (code, cp))
    if i % 8 == 7:
        out.write("\n")
out.write("\n};\n")
out.write("static const int kCp932PairCount = %d;\n" % len(items))
out.write("#endif\n")
path = r"C:\Users\woo31\openbgi\src\os\android\cp932_table.h"
open(path, "w", encoding="utf-8").write(out.getvalue())
print("pairs:", len(items), "=>", path, os.path.getsize(path), "bytes")
